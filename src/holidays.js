// ── 自我檢查（維護後執行：node --experimental-vm-modules 或直接在瀏覽器 console）──
export function selfCheck(year) {
  const issues = [];
  const data = H_YEAR[year];
  if (!data) { issues.push(`H_YEAR 缺少 ${year} 年資料`); return issues; }
  for (const key of Object.keys(data)) {
    if (!/^\d{2}-\d{2}$/.test(key)) issues.push(`${year} 的 key 格式錯誤：${key}（應為 MM-DD）`);
    const [mm, dd] = key.split("-").map(Number);
    if (mm < 1 || mm > 12 || dd < 1 || dd > 31) issues.push(`${year} 的日期不合法：${key}`);
  }
  if (SCHEDULE_END.year < year) issues.push(`SCHEDULE_END (${SCHEDULE_END.year}) 未延伸至 ${year}`);
  return issues.length ? issues : [`✓ ${year} 年資料檢查通過`];
}
