// ── 查詢函式（不需維護） ────────────────────────────────────────────
export function isWeekend(y, m, d) {
  const day = new Date(y, m, d).getDay();
  return day === 0 || day === 6;
}

export function getHolidayName(y, m, d) {
  const k = `${String(m + 1).padStart(2, "0")}-${String(d).padStart(2, "0")}`;
  return H_FIXED[k] || (H_YEAR[y] && H_YEAR[y][k]) || null;
}

export function isHoliday(y, m, d) {
  return !!getHolidayName(y, m, d);
}

// 日期類型：holiday（國定假日）> weekend（週末）> weekday（平日）
export function dayType(y, m, d) {
  if (isHoliday(y, m, d)) return "holiday";
  if (isWeekend(y, m, d)) return "weekend";
  return "weekday";
}

